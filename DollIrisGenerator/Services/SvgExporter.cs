    public static class SvgExporter
    {
        private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        public static string GenerateSingleEyeSvg(IrisParameters p, bool isRightEye, bool includePrintGuides = false)
        {
            double sizeMm = p.SizeMm;
            double widthMm = sizeMm;
            double heightMm = sizeMm;

            if (p.Shape == IrisShape.VerticalOval) heightMm *= p.AspectRatio;
            else if (p.Shape == IrisShape.HorizontalOval) widthMm *= p.AspectRatio;

            // Canvas holds the tilted footprint so a tilted oval is not cut off
            var (footW, footH) = SheetLayout.GetEyeFootprintMm(p);
            double paddingMm = 2.0;
            double totalWidthMm = footW + paddingMm * 2.0;
            double totalHeightMm = footH + paddingMm * 2.0;

            var sb = new StringBuilder();
            sb.AppendLine($@"<?xml version=""1.0"" encoding=""UTF-8"" standalone=""no""?>");
            sb.AppendLine($@"<svg width=""{totalWidthMm.ToString("F2", Inv)}mm"" height=""{totalHeightMm.ToString("F2", Inv)}mm"" viewBox=""0 0 {totalWidthMm.ToString("F2", Inv)} {totalHeightMm.ToString("F2", Inv)}"" xmlns=""http://www.w3.org/2000/svg"">");
            sb.AppendLine($@"  <!-- Generated by Doll Iris Atelier - Parametric Doll Eye -->");

            string eyeId = isRightEye ? "eye_right" : "eye_left";
            double cx = totalWidthMm / 2.0;
            double cy = totalHeightMm / 2.0;
            double rx = widthMm / 2.0;
            double ry = heightMm / 2.0;

            AppendIrisSvg(sb, eyeId, cx, cy, rx, ry, p, isRightEye, includePrintGuides);

            sb.AppendLine("</svg>");
            return sb.ToString();
        }

        public static string GeneratePairSvg(IrisParameters p, bool includePrintGuides = false, double pairSpacingMm = 4.0)
        {
            double sizeMm = p.SizeMm;
            double widthMm = sizeMm;
            double heightMm = sizeMm;

            if (p.Shape == IrisShape.VerticalOval) heightMm *= p.AspectRatio;
            else if (p.Shape == IrisShape.HorizontalOval) widthMm *= p.AspectRatio;

            // Canvas and eye spacing use the tilted footprint so tilted ovals are not cut off or overlapping
            var (footW, footH) = SheetLayout.GetEyeFootprintMm(p);
            double paddingMm = 3.0;
            double totalWidthMm = (footW * 2.0) + pairSpacingMm + (paddingMm * 2.0);
            double totalHeightMm = footH + (paddingMm * 2.0);

            var sb = new StringBuilder();
            sb.AppendLine($@"<?xml version=""1.0"" encoding=""UTF-8"" standalone=""no""?>");
            sb.AppendLine($@"<svg width=""{totalWidthMm.ToString("F2", Inv)}mm"" height=""{totalHeightMm.ToString("F2", Inv)}mm"" viewBox=""0 0 {totalWidthMm.ToString("F2", Inv)} {totalHeightMm.ToString("F2", Inv)}"" xmlns=""http://www.w3.org/2000/svg"">");
            sb.AppendLine($@"  <!-- Generated by Doll Iris Atelier - Symmetrical / Odd-Eye Pair -->");

            double rx = widthMm / 2.0;
            double ry = heightMm / 2.0;
            double cy = totalHeightMm / 2.0;

            // Left eye
            double leftCx = paddingMm + footW / 2.0;
            AppendIrisSvg(sb, "left_eye", leftCx, cy, rx, ry, p, false, includePrintGuides);

            // Right eye (Mirrored or Odd-Eye)
            double rightCx = leftCx + footW + pairSpacingMm;
            AppendIrisSvg(sb, "right_eye", rightCx, cy, rx, ry, p, true, includePrintGuides);

            sb.AppendLine("</svg>");
            return sb.ToString();
        }

        private static void AppendIrisSvg(
            StringBuilder sb,
            string idPrefix,
            double cx,
            double cy,
            double rx,
            double ry,
            IrisParameters p,
            bool isRightEye,
            bool includePrintGuides)
        {
            double baseR = Math.Min(rx, ry);

            // Odd-Eye Mode Overrides for Right Eye (with strict Hex Color Sanitization against XML injection)
            bool useOddEye = isRightEye && p.IsOddEye;
            string effectiveBaseColor = GeometryHelper.SanitizeColorHex(useOddEye ? p.OddEyeBaseColor : p.BaseColor, "#2979FF");
            string effectiveInnerColor = GeometryHelper.SanitizeColorHex(useOddEye ? p.OddEyeInnerColor : p.InnerColor, "#80D8FF");
            string effectiveOuterColor = GeometryHelper.SanitizeColorHex(useOddEye ? p.OddEyeOuterColor : p.OuterColor, "#0D47A1");
            string effectiveRayColor = GeometryHelper.SanitizeColorHex(useOddEye ? p.OddEyeRayColor : p.RayColor, "#B3E5FC");
            string effectiveBottomColor = GeometryHelper.SanitizeColorHex(useOddEye ? p.OddEyeBottomHighlightColor : p.BottomHighlightColor, "#B3E5FC");
            string safeLimbalColor = GeometryHelper.SanitizeColorHex(p.LimbalRingColor, "#051636");
            string safePupilColor = GeometryHelper.SanitizeColorHex(p.PupilColor, "#060A18");
            string safeParticleColor = GeometryHelper.SanitizeColorHex(p.ParticleColor, "#FFFFFF");
            string safeLensColor = GeometryHelper.SanitizeColorHex(p.LensRingColor, "#FFFFFF");
            int effectiveSeed = useOddEye ? (p.Seed + p.OddEyeSeedOffset) : p.Seed;

            // Tilt rotation angle
            double tilt = p.TiltAngle;
            if (isRightEye) tilt = -tilt;
            string tiltAttr = Math.Abs(tilt) > 0.05 ? $@" transform=""rotate({tilt.ToString("F1", Inv)}, {cx.ToString("F3", Inv)}, {cy.ToString("F3", Inv)})""" : "";

            string clipId = $"{idPrefix}_clip";
            string radGradId = $"{idPrefix}_rad_grad";
            string upperShadowId = $"{idPrefix}_shadow_grad";
            string bottomGlowId = $"{idPrefix}_glow_grad";

            sb.AppendLine("  <defs>");
            // Boundary clip
            sb.AppendLine($@"    <clipPath id=""{clipId}"">");
            sb.AppendLine($@"      <ellipse cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{rx.ToString("F3", Inv)}"" ry=""{ry.ToString("F3", Inv)}"" />");
            sb.AppendLine("    </clipPath>");

            // Base Radial Gradient
            sb.AppendLine($@"    <radialGradient id=""{radGradId}"" cx=""50%"" cy=""42%"" r=""55%"">");
            sb.AppendLine($@"      <stop offset=""0%"" stop-color=""{effectiveInnerColor}"" />");
            sb.AppendLine($@"      <stop offset=""{(p.InnerGradientRadius * 40.0).ToString("F1", Inv)}%"" stop-color=""{effectiveInnerColor}"" />");
            sb.AppendLine($@"      <stop offset=""{(p.InnerGradientRadius * 100.0).ToString("F1", Inv)}%"" stop-color=""{effectiveBaseColor}"" />");
            sb.AppendLine($@"      <stop offset=""{(p.OuterGradientRadius * 100.0).ToString("F1", Inv)}%"" stop-color=""{effectiveOuterColor}"" />");
            sb.AppendLine($@"      <stop offset=""100%"" stop-color=""{effectiveOuterColor}"" />");
            sb.AppendLine("    </radialGradient>");

            // Upper Shadow
            sb.AppendLine($@"    <linearGradient id=""{upperShadowId}"" x1=""0"" y1=""0"" x2=""0"" y2=""1"">");
            sb.AppendLine($@"      <stop offset=""0%"" stop-color=""#000000"" stop-opacity=""0.65"" />");
            sb.AppendLine($@"      <stop offset=""65%"" stop-color=""#000000"" stop-opacity=""0"" />");
            sb.AppendLine("    </linearGradient>");

            // Lower Glow
            sb.AppendLine($@"    <linearGradient id=""{bottomGlowId}"" x1=""0"" y1=""0"" x2=""0"" y2=""1"">");
            sb.AppendLine($@"      <stop offset=""45%"" stop-color=""{effectiveBottomColor}"" stop-opacity=""0"" />");
            sb.AppendLine($@"      <stop offset=""100%"" stop-color=""{effectiveBottomColor}"" stop-opacity=""{p.BottomHighlightIntensity.ToString("F2", Inv)}"" />");
            sb.AppendLine("    </linearGradient>");

            sb.AppendLine("  </defs>");

            // Start Group with tilt if specified
            sb.AppendLine($@"  <g id=""{idPrefix}""{tiltAttr}>");
            sb.AppendLine($@"    <g id=""{idPrefix}_clipped"" clip-path=""url(#{clipId})"">");

            // Base Background
            sb.AppendLine($@"      <ellipse id=""{idPrefix}_base"" cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{rx.ToString("F3", Inv)}"" ry=""{ry.ToString("F3", Inv)}"" fill=""url(#{radGradId})"" />");
            sb.AppendLine($@"      <ellipse id=""{idPrefix}_upper_shadow"" cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{rx.ToString("F3", Inv)}"" ry=""{ry.ToString("F3", Inv)}"" fill=""url(#{upperShadowId})"" />");
            if (p.BottomHighlightIntensity > 0.01)
            {
                sb.AppendLine($@"      <ellipse id=""{idPrefix}_bottom_glow"" cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{rx.ToString("F3", Inv)}"" ry=""{ry.ToString("F3", Inv)}"" fill=""url(#{bottomGlowId})"" />");
            }

            // Radial Rays
            if (p.RayCount > 0 && p.RayIntensity > 0.01)
            {
                sb.AppendLine($@"      <g id=""{idPrefix}_rays"" stroke=""{effectiveRayColor}"" stroke-width=""{(p.RayThickness * WpfIrisRenderer.MmPerStyleUnit).ToString("F3", Inv)}"" stroke-linecap=""round"" opacity=""{p.RayIntensity.ToString("F2", Inv)}"">");
                var rayRng = new Random(effectiveSeed);
                double pupilR = baseR * p.PupilSizeRatio;
                double innerR = Math.Max(pupilR * 0.85, baseR * p.RayInnerRadiusRatio);
                double outerR = baseR * p.RayLengthRatio;

                for (int i = 0; i < p.RayCount; i++)
                {
                    double baseAngle = (2.0 * Math.PI * i) / p.RayCount;
                    double jitter = (rayRng.NextDouble() - 0.5) * (p.RayRandomness * 0.5);
                    double angle = baseAngle + jitter;
                    if (isRightEye) angle = Math.PI - angle;

                    double lenVariation = 1.0 + (rayRng.NextDouble() - 0.5) * p.RayRandomness * 0.6;
                    double curOuterR = Math.Min(baseR * 0.96, outerR * lenVariation);
                    double curInnerR = innerR * (0.9 + rayRng.NextDouble() * 0.2);

                    double cosA = Math.Cos(angle);
                    double sinA = Math.Sin(angle);

                    double x1 = cx + curInnerR * cosA * (rx / baseR);
                    double y1 = cy + curInnerR * sinA * (ry / baseR);
                    double x2 = cx + curOuterR * cosA * (rx / baseR);
                    double y2 = cy + curOuterR * sinA * (ry / baseR);

                    sb.AppendLine($@"        <line x1=""{x1.ToString("F3", Inv)}"" y1=""{y1.ToString("F3", Inv)}"" x2=""{x2.ToString("F3", Inv)}"" y2=""{y2.ToString("F3", Inv)}"" />");
                }
                sb.AppendLine("      </g>");
            }

            // Lens-Style Pattern (Fresnel Rings)
            if (p.LensPatternEnabled && p.LensRingIntensity > 0.01)
            {
                sb.AppendLine($@"      <g id=""{idPrefix}_lens_rings"" stroke=""{safeLensColor}"" stroke-width=""{(p.LensRingWidth * WpfIrisRenderer.MmPerStyleUnit).ToString("F3", Inv)}"" opacity=""{p.LensRingIntensity.ToString("F2", Inv)}"" fill=""none"">");
                double pupilR = baseR * p.PupilSizeRatio;
                double ringSpan = (baseR * 0.92) - pupilR;

                for (int k = 1; k <= p.LensRingCount; k++)
                {
                    double progress = Math.Pow((double)k / p.LensRingCount, 0.82);
                    double ringR = pupilR + ringSpan * progress;
                    double ringRx = ringR * (rx / baseR);
                    double ringRy = ringR * (ry / baseR);

                    string dashAttr = (k % 2 == 1) ? @" stroke-dasharray=""1.5,1.0""" : "";
                    sb.AppendLine($@"        <ellipse cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{ringRx.ToString("F3", Inv)}"" ry=""{ringRy.ToString("F3", Inv)}""{dashAttr} />");
                }
                sb.AppendLine("      </g>");
            }

            // Limbal Ring
            if (p.LimbalRingThickness > 0.005 && p.LimbalRingOpacity > 0.01)
            {
                double ringWidth = baseR * p.LimbalRingThickness;
                sb.AppendLine($@"      <ellipse id=""{idPrefix}_limbal_ring"" cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{rx.ToString("F3", Inv)}"" ry=""{ry.ToString("F3", Inv)}"" fill=""none"" stroke=""{safeLimbalColor}"" stroke-width=""{(ringWidth * 2.0).ToString("F3", Inv)}"" opacity=""{p.LimbalRingOpacity.ToString("F2", Inv)}"" />");
            }

            // Pupil
            if (p.PupilSizeRatio > 0.01 && p.PupilOpacity > 0.01)
            {
                double prx = baseR * p.PupilSizeRatio;
                double pry = baseR * p.PupilSizeRatio;
                if (p.Shape == IrisShape.VerticalOval) pry *= p.AspectRatio;
                else if (p.Shape == IrisShape.HorizontalOval) prx *= p.AspectRatio;

                sb.AppendLine($@"      <g id=""{idPrefix}_pupil"" fill=""{safePupilColor}"" opacity=""{p.PupilOpacity.ToString("F2", Inv)}"">");
                switch (p.PupilShape)
                {
                    case PupilShape.VerticalOval:
                        sb.AppendLine($@"        <ellipse cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{(prx * 0.75).ToString("F3", Inv)}"" ry=""{(pry * 1.25).ToString("F3", Inv)}"" />");
                        break;
                    case PupilShape.CatSlit:
                        double sx = prx * 0.45;
                        double sy = pry * 1.15;
                        sb.AppendLine($@"        <path d=""M {cx.ToString("F3", Inv)},{(cy - sy).ToString("F3", Inv)} Q {(cx + sx * 1.4).ToString("F3", Inv)},{cy.ToString("F3", Inv)} {cx.ToString("F3", Inv)},{(cy + sy).ToString("F3", Inv)} Q {(cx - sx * 1.4).ToString("F3", Inv)},{cy.ToString("F3", Inv)} {cx.ToString("F3", Inv)},{(cy - sy).ToString("F3", Inv)} Z"" />");
                        break;
                    case PupilShape.Heart:
                        sb.AppendLine(BuildSvgHeart(cx, cy, prx * 0.95));
                        break;
                    case PupilShape.Star:
                        sb.AppendLine(BuildSvgStar5(cx, cy, prx * 1.05));
                        break;
                    case PupilShape.Round:
                    default:
                        sb.AppendLine($@"        <ellipse cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{prx.ToString("F3", Inv)}"" ry=""{pry.ToString("F3", Inv)}"" />");
                        break;
                }
                sb.AppendLine("      </g>");
            }

            // Particles / Glitter
            if (p.ParticleCount > 0 && p.ParticleOpacity > 0.01)
            {
                sb.AppendLine($@"      <g id=""{idPrefix}_glitter"" fill=""{safeParticleColor}"" opacity=""{p.ParticleOpacity.ToString("F2", Inv)}"">");
                var pRng = new Random(effectiveSeed + 1000);
                double minR = baseR * p.PupilSizeRatio * 0.95;
                double maxR = baseR * p.ParticleRadiusRatio;

                for (int i = 0; i < p.ParticleCount; i++)
                {
                    double dist = minR + pRng.NextDouble() * Math.Max(0.5, maxR - minR);
                    double angle = pRng.NextDouble() * 2.0 * Math.PI;
                    if (isRightEye) angle = Math.PI - angle;

                    double pSize = (p.ParticleMinSize + pRng.NextDouble() * Math.Max(0.1, p.ParticleMaxSize - p.ParticleMinSize)) * WpfIrisRenderer.MmPerStyleUnit;
                    double px = cx + dist * Math.Cos(angle) * (rx / baseR);
                    double py = cy + dist * Math.Sin(angle) * (ry / baseR);

                    if (i % 5 == 0)
                    {
                        sb.AppendLine(BuildSvgStar4(px, py, pSize * 1.5, 0.25));
                    }
                    else
                    {
                        sb.AppendLine($@"        <circle cx=""{px.ToString("F3", Inv)}"" cy=""{py.ToString("F3", Inv)}"" r=""{(pSize * 0.5).ToString("F3", Inv)}"" />");
                    }
                }
                sb.AppendLine("      </g>");
            }

            // Decorative Symbols
            if (p.Symbols != null)
            {
                foreach (var symbol in p.Symbols)
                {
                    if (!symbol.Enabled || symbol.Type == SymbolType.None || symbol.Opacity <= 0.01)
                        continue;

                    double posX = symbol.PositionX;
                    double rot = symbol.Rotation;
                    if (isRightEye)
                    {
                        posX = -posX;
                        rot = -rot;
                    }

                    double symX = cx + posX * rx;
                    double symY = cy + symbol.PositionY * ry;
                    double symRadius = baseR * symbol.Size;
                    string safeSymColor = GeometryHelper.SanitizeColorHex(symbol.Color, "#FFFFFF");

                    sb.AppendLine($@"      <g id=""{idPrefix}_symbol_{symbol.Type}"" fill=""{safeSymColor}"" opacity=""{symbol.Opacity.ToString("F2", Inv)}"">");

                    for (int c = 0; c < symbol.Count; c++)
                    {
                        double curX = symX;
                        double curY = symY;
                        double curRot = rot;

                        if (symbol.Count > 1)
                        {
                            double offsetAngle = (2.0 * Math.PI * c) / symbol.Count;
                            if (isRightEye) offsetAngle = Math.PI - offsetAngle;
                            curX += symRadius * 1.4 * Math.Cos(offsetAngle);
                            curY += symRadius * 1.4 * Math.Sin(offsetAngle);
                        }

                        string rotAttr = Math.Abs(curRot) > 0.1 ? $@" transform=""rotate({curRot.ToString("F1", Inv)}, {curX.ToString("F3", Inv)}, {curY.ToString("F3", Inv)})""" : "";
                        switch (symbol.Type)
                        {
                            case SymbolType.Star4:
                                sb.AppendLine(BuildSvgStar4(curX, curY, symRadius, 0.28, rotAttr));
                                break;
                            case SymbolType.Star5:
                                sb.AppendLine(BuildSvgStar5(curX, curY, symRadius, rotAttr));
                                break;
                            case SymbolType.Heart:
                                sb.AppendLine(BuildSvgHeart(curX, curY, symRadius, rotAttr));
                                break;
                            case SymbolType.Moon:
                                sb.AppendLine(BuildSvgMoon(curX, curY, symRadius, isRightEye, rotAttr));
                                break;
                            case SymbolType.Cross:
                                sb.AppendLine(BuildSvgCross(curX, curY, symRadius, rotAttr));
                                break;
                            case SymbolType.Diamond:
                                sb.AppendLine(BuildSvgDiamond(curX, curY, symRadius * 0.7, symRadius, rotAttr));
                                break;
                            case SymbolType.SakuraPetal:
                                sb.AppendLine(BuildSvgSakuraPetal(curX, curY, symRadius, rotAttr));
                                break;
                        }
                    }
                    sb.AppendLine("      </g>");
                }
            }

            // Close boundary clip group
            sb.AppendLine("    </g>");

            // Highlights (Drawn on top without clipping)
            if (p.Highlights != null)
            {
                sb.AppendLine($@"    <g id=""{idPrefix}_highlights"">");
                foreach (var h in p.Highlights)
                {
                    if (!h.Enabled || h.Opacity <= 0.01 || h.Size <= 0.005)
                        continue;

                    double posX = h.PositionX;
                    double rot = h.Rotation;

                    if (isRightEye && p.MirrorHighlightsWithIris)
                    {
                        posX = -posX;
                        rot = -rot;
                    }

                    double hx = cx + posX * rx;
                    double hy = cy + h.PositionY * ry;
                    double hRadius = baseR * h.Size;
                    string safeHColor = GeometryHelper.SanitizeColorHex(h.Color, "#FFFFFF");

                    string rotAttr = Math.Abs(rot) > 0.1 ? $@" transform=""rotate({rot.ToString("F1", Inv)}, {hx.ToString("F3", Inv)}, {hy.ToString("F3", Inv)})""" : "";

                    switch (h.Shape)
                    {
                        case HighlightShape.Oval:
                            double hrx = hRadius * (h.AspectRatio > 0 ? h.AspectRatio : 1.0);
                            sb.AppendLine($@"      <ellipse cx=""{hx.ToString("F3", Inv)}"" cy=""{hy.ToString("F3", Inv)}"" rx=""{hrx.ToString("F3", Inv)}"" ry=""{hRadius.ToString("F3", Inv)}"" fill=""{safeHColor}"" opacity=""{h.Opacity.ToString("F2", Inv)}""{rotAttr} />");
                            break;
                        case HighlightShape.Star4:
                            sb.AppendLine(BuildSvgStar4(hx, hy, hRadius, 0.22, rotAttr, safeHColor, h.Opacity));
                            break;
                        case HighlightShape.Rhombus:
                            sb.AppendLine(BuildSvgDiamond(hx, hy, hRadius * 0.65, hRadius, rotAttr, safeHColor, h.Opacity));
                            break;
                        case HighlightShape.Circle:
                        default:
                            sb.AppendLine($@"      <ellipse cx=""{hx.ToString("F3", Inv)}"" cy=""{hy.ToString("F3", Inv)}"" rx=""{hRadius.ToString("F3", Inv)}"" ry=""{hRadius.ToString("F3", Inv)}"" fill=""{safeHColor}"" opacity=""{h.Opacity.ToString("F2", Inv)}""{rotAttr} />");
                            break;
                    }
                }
                sb.AppendLine("    </g>");
            }

            // Print Guides
            if (includePrintGuides)
            {
                sb.AppendLine($@"    <g id=""{idPrefix}_guides"">");
                sb.AppendLine($@"      <ellipse cx=""{cx.ToString("F3", Inv)}"" cy=""{cy.ToString("F3", Inv)}"" rx=""{rx.ToString("F3", Inv)}"" ry=""{ry.ToString("F3", Inv)}"" fill=""none"" stroke=""#999999"" stroke-width=""0.15"" stroke-dasharray=""2,2"" />");
                double markLen = baseR * 0.15;
                sb.AppendLine($@"      <line x1=""{(cx - markLen).ToString("F3", Inv)}"" y1=""{cy.ToString("F3", Inv)}"" x2=""{(cx + markLen).ToString("F3", Inv)}"" y2=""{cy.ToString("F3", Inv)}"" stroke=""#777777"" stroke-width=""0.1"" />");
                sb.AppendLine($@"      <line x1=""{cx.ToString("F3", Inv)}"" y1=""{(cy - markLen).ToString("F3", Inv)}"" x2=""{cx.ToString("F3", Inv)}"" y2=""{(cy + markLen).ToString("F3", Inv)}"" stroke=""#777777"" stroke-width=""0.1"" />");
                sb.AppendLine("    </g>");
            }

            // Close tilt group
            sb.AppendLine("  </g>");
        }

        private static string BuildSvgStar4(double cx, double cy, double radius, double innerRatio, string transform = "", string? fill = null, double opacity = 1.0)
        {
            var sb = new StringBuilder();
            sb.Append("        <polygon points=\"");
            for (int i = 0; i < 8; i++)
            {
                double angle = i * Math.PI / 4.0 - Math.PI / 2.0;
                double r = (i % 2 == 0) ? radius : radius * innerRatio;
                double x = cx + r * Math.Cos(angle);
                double y = cy + r * Math.Sin(angle);
                sb.Append($"{x.ToString("F3", Inv)},{y.ToString("F3", Inv)} ");
            }
            sb.Append("\"");
            if (fill != null) sb.Append($@" fill=""{fill}"" opacity=""{opacity.ToString("F2", Inv)}""");
            if (!string.IsNullOrEmpty(transform)) sb.Append(transform);
            sb.Append(" />");
            return sb.ToString();
        }

        private static string BuildSvgStar5(double cx, double cy, double radius, string transform = "", string? fill = null, double opacity = 1.0)
        {
            var sb = new StringBuilder();
            sb.Append("        <polygon points=\"");
            for (int i = 0; i < 10; i++)
            {
                double angle = i * Math.PI / 5.0 - Math.PI / 2.0;
                double r = (i % 2 == 0) ? radius : radius * 0.40;
                double x = cx + r * Math.Cos(angle);
                double y = cy + r * Math.Sin(angle);
                sb.Append($"{x.ToString("F3", Inv)},{y.ToString("F3", Inv)} ");
            }
            sb.Append("\"");
            if (fill != null) sb.Append($@" fill=""{fill}"" opacity=""{opacity.ToString("F2", Inv)}""");
            if (!string.IsNullOrEmpty(transform)) sb.Append(transform);
            sb.Append(" />");
            return sb.ToString();
        }

        private static string BuildSvgHeart(double cx, double cy, double radius, string transform = "", string? fill = null, double opacity = 1.0)
        {
            double topY = cy - radius * 0.45;
            double botY = cy + radius * 0.85;
            double lx = cx - radius * 0.95;
            double rx = cx + radius * 0.95;

            var sb = new StringBuilder();
            sb.Append($@"        <path d=""M {cx.ToString("F3", Inv)},{botY.ToString("F3", Inv)} C {(lx * 1.05).ToString("F3", Inv)},{(botY * 0.2 + cy * 0.8).ToString("F3", Inv)} {lx.ToString("F3", Inv)},{(topY * 1.3).ToString("F3", Inv)} {cx.ToString("F3", Inv)},{topY.ToString("F3", Inv)} C {rx.ToString("F3", Inv)},{(topY * 1.3).ToString("F3", Inv)} {(rx * 1.05).ToString("F3", Inv)},{(botY * 0.2 + cy * 0.8).ToString("F3", Inv)} {cx.ToString("F3", Inv)},{botY.ToString("F3", Inv)} Z""");
            if (fill != null) sb.Append($@" fill=""{fill}"" opacity=""{opacity.ToString("F2", Inv)}""");
            if (!string.IsNullOrEmpty(transform)) sb.Append(transform);
            sb.Append(" />");
            return sb.ToString();
        }

        private static string BuildSvgMoon(double cx, double cy, double radius, bool isRightEye, string transform = "")
        {
            double topY = cy - radius;
            double botY = cy + radius;
            var sb = new StringBuilder();
            sb.Append($@"        <path d=""M {cx.ToString("F3", Inv)},{topY.ToString("F3", Inv)} A {radius.ToString("F3", Inv)} {radius.ToString("F3", Inv)} 0 0 {(isRightEye ? "0" : "1")} {cx.ToString("F3", Inv)},{botY.ToString("F3", Inv)} A {(radius * 0.82).ToString("F3", Inv)} {(radius * 1.05).ToString("F3", Inv)} 0 0 {(isRightEye ? "1" : "0")} {cx.ToString("F3", Inv)},{topY.ToString("F3", Inv)} Z""");
